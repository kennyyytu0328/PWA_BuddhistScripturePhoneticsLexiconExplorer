/** 字型子集的純函式：用字蒐集、分檔、unicode-range 與 @font-face 產生。 */

export type CodePoints = ReadonlySet<number>

/** 必須由打包字型涵蓋的字：漢字與中日韓／全形標點（拉丁等不在此限，Q-RDR-016）。 */
export function isHanOrFullwidth(cp: number): boolean {
  return (
    (cp >= 0x3400 && cp <= 0x4dbf) ||
    (cp >= 0x4e00 && cp <= 0x9fff) ||
    (cp >= 0xf900 && cp <= 0xfaff) ||
    (cp >= 0x20000 && cp <= 0x2fa1f) ||
    (cp >= 0x3000 && cp <= 0x303f) ||
    (cp >= 0xff01 && cp <= 0xff60) ||
    (cp >= 0xffe0 && cp <= 0xffe6)
  )
}

/** 注音符號（含擴充）。 */
export function isBopomofo(cp: number): boolean {
  return (cp >= 0x3100 && cp <= 0x312f) || (cp >= 0x31a0 && cp <= 0x31bf)
}

/** 缺字即中止建置的字。 */
export function isRequired(cp: number): boolean {
  return isHanOrFullwidth(cp) || isBopomofo(cp)
}

/** 私用區：DFB 原檔的缺字，畫面改以「〓」顯示，不進子集。 */
export function isPrivateUse(cp: number): boolean {
  return cp >= 0xe000 && cp <= 0xf8ff
}

/** 遞迴取出 JSON 值中的全部字串。 */
export function collectStrings(value: unknown): string[] {
  if (typeof value === 'string') return [value]
  if (Array.isArray(value)) return value.flatMap(collectStrings)
  if (value && typeof value === 'object') return Object.values(value).flatMap(collectStrings)
  return []
}

/** 字串的用字集合；略過控制字元與私用區。 */
export function codePointsOf(texts: Iterable<string>): Set<number> {
  const out = new Set<number>()
  for (const text of texts) {
    for (const ch of text) {
      const cp = ch.codePointAt(0)!
      if (cp >= 0x20 && cp !== 0x7f && !isPrivateUse(cp)) out.add(cp)
    }
  }
  return out
}

export function union(...sets: CodePoints[]): Set<number> {
  return new Set(sets.flatMap((s) => [...s]))
}

export function difference(a: CodePoints, b: CodePoints): Set<number> {
  return new Set([...a].filter((cp) => !b.has(cp)))
}

/** 原始碼中的 CJK／注音字元；先去掉註解，避免註解用字進入子集。 */
export function uiCodePointsFromSource(source: string): Set<number> {
  const code = source.replace(/\/\*[\s\S]*?\*\//g, '').replace(/(^|\s)\/\/.*$/gm, '$1')
  return new Set([...codePointsOf([code])].filter(isRequired))
}

/** 把用字集合壓成 `U+4E00-4E05,U+4E10` 形式。 */
export function toUnicodeRange(cps: CodePoints): string {
  const sorted = [...cps].sort((a, b) => a - b)
  const hex = (n: number) => n.toString(16).toUpperCase().padStart(4, '0')
  const parts: string[] = []
  for (let i = 0; i < sorted.length; ) {
    let j = i
    while (j + 1 < sorted.length && sorted[j + 1] === sorted[j] + 1) j++
    parts.push(i === j ? `U+${hex(sorted[i])}` : `U+${hex(sorted[i])}-${hex(sorted[j])}`)
    i = j + 1
  }
  return parts.join(',')
}

export interface FaceSpec {
  family: string
  file: string
  codePoints: CodePoints
}

export function buildCss(faces: FaceSpec[]): string {
  const blocks = faces.map(
    (f) => `@font-face {
  font-family: '${f.family}';
  src: url('./${f.file}') format('woff2');
  font-style: normal;
  font-weight: 400;
  font-display: block;
  unicode-range: ${toUnicodeRange(f.codePoints)};
}`,
  )
  return `/* generated by scripts/build-fonts.ts - do not edit */\n${blocks.join('\n')}\n`
}

export interface PunctGlyph {
  char: string
  /** 字形邊界框中心，橫向，佔字格寬的比例（0 = 左、1 = 右） */
  x: number
  /** 字形邊界框中心，縱向，由字格上緣起算的比例（0 = 上、1 = 下） */
  y: number
}

/** 直排標點應落在字格的右上：橫向 > 0.5 且縱向 < 0.5（Q-RDR-019）。回傳不合者的說明。 */
export function misplacedPunct(glyphs: PunctGlyph[]): string[] {
  return glyphs
    .filter((g) => !(g.x > 0.5 && g.y < 0.5))
    .map((g) => `標點「${g.char}」的直排字形中心在 (${g.x.toFixed(2)}, ${g.y.toFixed(2)})，未落在右上`)
}
